//! Docutils-native XML and pseudo-XML builders (Phase 25).
//!
//! Upstream `sphinx/builders/xml.py` defines two builders:
//!
//! * `XMLBuilder` uses `docutils.writers.docutils_xml.XMLTranslator`, which
//!   emits a real XML document (XML declaration, Docutils DOCTYPE, a generated
//!   comment, explicit start/end tags and escaped attributes).
//! * `PseudoXMLBuilder` is a thin subclass that only overrides `_translate` to
//!   call `document.pformat()` — the frozen Phase 03 pseudo-XML format.
//!
//! Both builders write one file per source document (`<docname>.xml` /
//! `<docname>.pseudoxml`) plus the standard `.doctrees` snapshots written by
//! the shared read pipeline. This module deliberately does **not** modify the
//! frozen §7 AST: the real-XML translator is additive and lives here.

use std::fs;
use std::path::{Path, PathBuf};

use scribe_ast::{AttributeValue, Document, Node, NodeId, NodeKind};
use scribe_config::Config;
use scribe_core::{
    expand_toctrees, normalize_citation_references, normalize_xref_literals, BuildEnvironment,
};

use crate::build_common::{no_title_warning_line, prepare, PreparedBuild};
use crate::error::{OutputError, OutputResult};
use crate::html::{BuildOptions, BuildResult};

/// Built-in domains injected as `xmlns:*` attributes by upstream's
/// `XMLBuilder.write_doc` (sorted, in the same order as a Python `dict` built
/// from `env.domains.sorted()`).
pub const XMLNS_DOMAINS: &[&str] = &[
    "c", "changeset", "citation", "cpp", "index", "js", "math", "py", "rst", "std",
];

/// Docutils DOCTYPE declaration emitted by `XMLTranslator.doctype`.
pub const DOCTYPE: &str = "<!DOCTYPE document PUBLIC \"+//IDN docutils.sourceforge.net//DTD Docutils Generic//EN//XML\" \"http://docutils.sourceforge.net/docs/ref/docutils.dtd\">\n";

/// The generator comment. The version is normalized by differential tests.
pub const GENERATOR_PREFIX: &str = "<!-- Generated by Docutils ";
pub const GENERATOR_SUFFIX: &str = " -->\n";

/// Builder for `-b xml` (real Docutils XML).
pub struct XmlBuilder;

impl XmlBuilder {
    /// Build all XML documents.
    pub fn build(
        options: &BuildOptions,
        config: &Config,
        env: &mut BuildEnvironment,
    ) -> OutputResult<BuildResult> {
        build_docs(options, config, env, "xml", ".xml", RenderMode::Xml)
    }
}

/// Builder for `-b pseudoxml` (Docutils `pformat`, Phase 03 format).
pub struct PseudoXmlBuilder;

impl PseudoXmlBuilder {
    /// Build all pseudo-XML documents.
    pub fn build(
        options: &BuildOptions,
        config: &Config,
        env: &mut BuildEnvironment,
    ) -> OutputResult<BuildResult> {
        build_docs(options, config, env, "pseudoxml", ".pseudoxml", RenderMode::PseudoXml)
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum RenderMode {
    Xml,
    PseudoXml,
}

fn build_docs(
    options: &BuildOptions,
    config: &Config,
    env: &mut BuildEnvironment,
    builder: &'static str,
    suffix: &str,
    mode: RenderMode,
) -> OutputResult<BuildResult> {
    let PreparedBuild { docnames, mut parsed, mut warnings, toctrees, .. } =
        prepare(options, config, env, builder)?;

    // Upstream resolves every `toctree` node before a writing builder emits the
    // doctree. The HTML5 writer renders the raw node directly (as
    // `toctree-wrapper`), so the expansion is applied only to the exported
    // doctree here — this keeps both writers free of double-wrapping.
    for docname in &docnames {
        if let Some(document) = parsed.get_mut(docname) {
            match expand_toctrees(document, docname, env, &toctrees) {
                Ok(expansion) => {
                    for (target, line) in expansion.no_title {
                        warnings.push(no_title_warning_line(docname, &target, line, &options.source_dir));
                    }
                }
                Err(error) => warnings.push(format!("{docname}: toctree expansion failed: {error}")),
            }
            if let Err(error) = normalize_citation_references(document) {
                warnings.push(format!("{docname}: citation reference normalization failed: {error}"));
            }
            if let Err(error) = normalize_xref_literals(document) {
                warnings.push(format!("{docname}: xref literal normalization failed: {error}"));
            }
        }
    }

    let pretty = config.get_bool("xml_pretty").unwrap_or(true);
    let mut written = Vec::new();
    for docname in &docnames {
        let Some(document) = parsed.get_mut(docname) else {
            continue;
        };
        // Upstream sets the document source to the absolute path of the
        // source file and injects the translation-progress and xmlns
        // attributes in `XMLBuilder.write_doc`. Doing this here keeps the
        // frozen AST untouched and makes the emitted files match the oracle
        // up to the (documented) path/version normalization.
        let source_path = env.doc2path(docname).map(Path::to_path_buf).unwrap_or_else(|| PathBuf::from(docname));
        {
            let root = document.root_mut();
            root.attrs.set_str("source", source_path.to_string_lossy().as_ref());
            root.attrs.set_str("translation_progress", "{'total': 0, 'translated': 0}");
            for domain in XMLNS_DOMAINS {
                root.attrs.set_str(
                    format!("xmlns:{domain}"),
                    "https://www.sphinx-doc.org/",
                );
            }
        }

        let text = match mode {
            RenderMode::Xml => render_xml(document, pretty)
                .map_err(|error| OutputError::config(builder, "xml", error.to_string()))?,
            RenderMode::PseudoXml => document
                .to_pseudoxml()
                .map_err(|error| OutputError::config(builder, "pseudoxml", error.to_string()))?,
        };

        let relative = Path::new(docname).with_extension(suffix.trim_start_matches('.'));
        let out_path = options.output_dir.join(&relative);
        if let Some(parent) = out_path.parent() {
            fs::create_dir_all(parent).map_err(|error| OutputError::io(builder, parent, error))?;
        }
        fs::write(&out_path, text)
            .map_err(|error| OutputError::io(builder, &out_path, error))?;
        written.push(relative);
    }

    Ok(BuildResult { written, built_docnames: docnames, warnings })
}

/// Render a document as real Docutils XML.
///
/// The implementation mirrors `.oracle-venv/.../docutils/writers/docutils_xml.py::XMLTranslator`
/// and `docutils.nodes.Element.starttag`: block nodes are indented on their
/// own lines; "simple" nodes (text elements plus `meta`/`image`/`colspec`/
/// `transition`) keep their text inline; inline nodes do not increase the
/// indentation level; fixed-text elements leave embedded newlines untouched.
pub fn render_xml(document: &Document, pretty: bool) -> Result<String, XmlRenderError> {
    let mut out = String::from("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    out.push_str(DOCTYPE);
    out.push_str(GENERATOR_PREFIX);
    out.push_str("0.23");
    out.push_str(GENERATOR_SUFFIX);

    let mut state = XmlState { pretty, level: 0, in_simple: 0, fixed_text: 0, out: &mut out };
    state.visit(document, document.root)?;
    // `default_departure` already appends the newline after `</document>`,
    // matching the oracle's single trailing newline.
    Ok(out)
}

/// Errors raised while rendering real XML (all are frozen-AST access errors).
#[derive(Debug, thiserror::Error)]
pub enum XmlRenderError {
    /// An arena access failed.
    #[error(transparent)]
    Ast(#[from] scribe_ast::AstError),
}

struct XmlState<'a> {
    pretty: bool,
    level: usize,
    in_simple: usize,
    fixed_text: usize,
    out: &'a mut String,
}

impl XmlState<'_> {
    fn indent(&self) -> String {
        if self.pretty {
            "    ".repeat(self.level)
        } else {
            String::new()
        }
    }

    fn newline(&self) -> &'static str {
        if self.pretty { "\n" } else { "" }
    }

    fn visit(&mut self, doc: &Document, id: NodeId) -> Result<(), XmlRenderError> {
        let node = doc.get(id)?;
        if node.kind == NodeKind::Text {
            let text = node.text_content().unwrap_or("");
            let escaped = escape_text(text);
            if self.pretty && self.fixed_text == 0 {
                let ind = "    ".repeat(self.level);
                self.out.push_str(&escaped.replace('\n', &format!("\n{ind}")));
            } else {
                self.out.push_str(&escaped);
            }
            return Ok(());
        }

        let is_inline = node.kind.is_inline();
        let is_simple = is_simple_node(node.kind);
        let is_fixed = is_fixed_text(node.kind);

        if self.in_simple == 0 && self.pretty {
            self.out.push_str(&self.indent());
        }
        self.out.push('<');
        self.out.push_str(node.kind.tag_name());
        emit_start_attrs(node, self.out);
        self.out.push('>');

        if !is_inline {
            self.level += 1;
        }
        if is_fixed {
            self.fixed_text += 1;
        }
        if is_simple {
            self.in_simple += 1;
        }
        if self.in_simple == 0 {
            self.out.push_str(self.newline());
        }

        // Text with inline element children (e.g. a title with emphasis) is
        // emitted inline, so `in_simple > 0` must suppress indentation of
        // every child tag as well.
        let children: Vec<NodeId> = node.children.iter().copied().filter(|&c| doc.is_live(c)).collect();
        for child in children {
            self.visit(doc, child)?;
        }

        if !is_inline {
            self.level -= 1;
        }
        if self.in_simple == 0 && self.pretty {
            self.out.push_str(&self.indent());
        }
        self.out.push_str("</");
        self.out.push_str(node.kind.tag_name());
        self.out.push('>');
        if is_fixed {
            self.fixed_text -= 1;
        }
        if is_simple {
            self.in_simple -= 1;
        }
        if self.in_simple == 0 {
            self.out.push_str(self.newline());
        }
        Ok(())
    }
}

/// Docutils' `simple_nodes` tuple plus `TextElement` kinds. A complete list of
/// `TextElement` subclasses relevant to the frozen AST; unknown kinds default
/// to block formatting (which is conservative and still well-formed XML).
fn is_simple_node(kind: NodeKind) -> bool {
    matches!(
        kind,
        // TextElement subclasses present in the frozen AST.
        NodeKind::Title
            | NodeKind::Subtitle
            | NodeKind::Paragraph
            | NodeKind::Term
            | NodeKind::FieldName
            | NodeKind::Attribution
            | NodeKind::Line
            | NodeKind::Reference
            | NodeKind::Rubric
            | NodeKind::Caption
            | NodeKind::Label
            | NodeKind::OptionString
            | NodeKind::OptionArgument
            | NodeKind::LiteralBlock
            | NodeKind::DoctestBlock
            | NodeKind::MathBlock
            | NodeKind::Comment
            | NodeKind::SubstitutionDefinition
            | NodeKind::Target
            | NodeKind::Emphasis
            | NodeKind::Strong
            | NodeKind::Literal
            | NodeKind::Inline
            | NodeKind::FootnoteReference
            | NodeKind::CitationReference
            | NodeKind::SubstitutionReference
            | NodeKind::Math
            | NodeKind::Problematic
            | NodeKind::Generated
            | NodeKind::DescInline
            // Upstream's extra `simple_nodes` tuple members.
            | NodeKind::Image
            | NodeKind::Colspec
            | NodeKind::TabularColSpec
            | NodeKind::Transition
    )
}

/// Elements whose text content preserves embedded newlines verbatim
/// (`nodes.FixedTextElement` plus `nodes.literal`).
fn is_fixed_text(kind: NodeKind) -> bool {
    matches!(
        kind,
        NodeKind::LiteralBlock
            | NodeKind::DoctestBlock
            | NodeKind::MathBlock
            | NodeKind::Comment
            | NodeKind::Raw
            | NodeKind::Literal
            | NodeKind::SubstitutionDefinition
            | NodeKind::DescSigLiteralString
    )
}

/// Emit attributes in sorted order exactly like `docutils.nodes.Element.starttag`
/// with `xml.sax.saxutils.quoteattr` as the quoting function.
fn emit_start_attrs(node: &Node, out: &mut String) {
    for (key, value) in node.attrs.iter() {
        if is_default_list(key, value) || is_internal(value) {
            continue;
        }
        let formatted = format_attribute_value(value);
        out.push(' ');
        out.push_str(key);
        out.push('=');
        out.push_str(&quote_attr(&formatted));
    }
}

fn is_default_list(key: &str, value: &AttributeValue) -> bool {
    matches!(value, AttributeValue::List(v) if v.is_empty())
        && matches!(key, "ids" | "classes" | "names" | "dupnames")
}

fn is_internal(value: &AttributeValue) -> bool {
    matches!(value, AttributeValue::NodeId(_) | AttributeValue::NodeIds(_))
}

fn format_attribute_value(value: &AttributeValue) -> String {
    match value {
        AttributeValue::Str(s) => s.clone(),
        AttributeValue::Bool(b) => if *b { "1" } else { "0" }.to_owned(),
        AttributeValue::Int(i) => i.to_string(),
        AttributeValue::Float(f) => f.to_string(),
        AttributeValue::List(values) => values.iter().map(|v| serial_escape(v)).collect::<Vec<_>>().join(" "),
        AttributeValue::NodeId(_) | AttributeValue::NodeIds(_) => String::new(),
        AttributeValue::Null => "True".to_owned(),
    }
}

/// Docutils `serial_escape`: double backslashes, escape internal spaces.
fn serial_escape(value: &str) -> String {
    value.replace('\\', r"\\").replace(' ', r"\ ")
}

/// `xml.sax.saxutils.escape` (text nodes): `&`, `<`, `>` only.
fn escape_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            _ => out.push(ch),
        }
    }
    out
}

/// `xml.sax.saxutils.quoteattr` (attribute values). Uses single quotes when
/// the value contains `"` but no `'`, exactly like the standard library.
fn quote_attr(value: &str) -> String {
    let use_single = value.contains('"') && !value.contains('\'');
    let quote = if use_single { '\'' } else { '"' };
    let mut out = String::with_capacity(value.len() + 2);
    out.push(quote);
    for ch in value.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '\n' => out.push_str("&#10;"),
            '\r' => out.push_str("&#13;"),
            '\t' => out.push_str("&#9;"),
            c if c == quote => {
                if quote == '"' { out.push_str("&quot;"); } else { out.push_str("&apos;"); }
            }
            c => out.push(c),
        }
    }
    out.push(quote);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn xml_has_declaration_doctype_and_closing_tags() {
        let mut doc = Document::new(Some("a&b.rst".into()));
        let _text = doc.new_text("a < b & c", Some(doc.root)).expect("valid root");
        let xml = render_xml(&doc, true).expect("render");
        assert!(xml.starts_with("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"));
        assert!(xml.contains("<!DOCTYPE document PUBLIC"));
        assert!(xml.contains("<!-- Generated by Docutils 0.23 -->"));
        assert!(xml.contains("<document source=\"a&amp;b.rst\">"));
        assert!(xml.contains("a &lt; b &amp; c"));
        assert!(xml.trim_end().ends_with("</document>"));
    }

    #[test]
    fn attribute_quoting_matches_sax_quoteattr() {
        assert_eq!(quote_attr("a b"), "\"a b\"");
        assert_eq!(quote_attr("a\"b"), "'a\"b'");
        assert_eq!(quote_attr("a\"b'c"), "\"a&quot;b'c\"");
        assert_eq!(quote_attr("a\nb"), "\"a&#10;b\"");
    }

    #[test]
    fn non_pretty_xml_has_no_indentation() {
        let doc = Document::new(None);
        let xml = render_xml(&doc, false).expect("render");
        assert!(xml.contains("<document>"));
        assert!(!xml.contains("    "));
    }
}

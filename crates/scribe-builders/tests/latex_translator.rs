//! Unit tests for the Phase 23 LaTeX translator and escaping layer.
//!
//! These construct frozen doctrees directly and assert the emitted LaTeX
//! structure without invoking the full build pipeline. See
//! `ARCHITECTURE.md` §29 for the node → command mapping and escaping rules.

use scribe_ast::{Document, NodeKind};
use scribe_builders::latex::{escape_latex, escape_latex_unicode, LatexContext, LaTeXTranslator, LatexEngine};
use scribe_config::Config;

fn ctx() -> LatexContext {
    LatexContext {
        docname: "index".to_owned(),
        config: Config::new(),
        engine: LatexEngine::PdfLatex,
        title: "Title".to_owned(),
        author: "Author".to_owned(),
        release: String::new(),
        date: String::new(),
        theme: "manual".to_owned(),
        extra_preamble: String::new(),
        use_sphinx_sty: false,
        numfig: false,
        language: "en".to_owned(),
        logo: None,
    }
}

fn body(doc: &Document) -> String {
    LaTeXTranslator::translate_body(doc, &ctx())
}

#[test]
fn preamble_has_expected_packages_and_structure() {
    let doc = Document::new(None);
    let tex = LaTeXTranslator::translate(&doc, &ctx());
    assert!(tex.starts_with("%% Generated by scribe"), "{tex}");
    assert!(tex.contains("\\documentclass[letterpaper,11pt]{report}"), "{tex}");
    for pkg in ["amsmath", "graphicx", "hyperref", "tabularx", "longtable", "makeidx"] {
        assert!(tex.contains(&format!("\\usepackage{{{pkg}}}")) || tex.contains(&format!("\\usepackage[T1]{{{pkg}}}")) || tex.contains(pkg), "missing {pkg}");
    }
    assert!(tex.contains("\\makeindex"), "{tex}");
    assert!(tex.contains("\\title{Title}"), "{tex}");
    assert!(tex.contains("\\author{Author}"), "{tex}");
    assert!(tex.contains("\\begin{document}"), "{tex}");
    assert!(tex.contains("\\end{document}"), "{tex}");
}

#[test]
fn empty_and_unicode_documents_do_not_panic() {
    let empty = Document::new(None);
    let tex = LaTeXTranslator::translate(&empty, &ctx());
    assert!(tex.contains("\\end{document}"));

    let mut doc = Document::new(None);
    let p = doc.add(NodeKind::Paragraph, Some(doc.root)).unwrap();
    doc.new_text("café 中文 ℯ ⁰ & # % $ _ { } ~ ^ \\", Some(p)).unwrap();
    let tex = LaTeXTranslator::translate(&doc, &ctx());
    // pdflatex output must be ASCII-only apart from the comment header.
    let body = tex.split("\\begin{document}").nth(1).unwrap();
    assert!(body.is_ascii(), "non-ASCII leaked into pdflatex body: {body}");
    assert!(body.contains("caf"), "{body}");
}

#[test]
fn inline_markup_commands() {
    let mut doc = Document::new(None);
    let p = doc.add(NodeKind::Paragraph, Some(doc.root)).unwrap();
    for (kind, text) in [
        (NodeKind::Emphasis, "em"),
        (NodeKind::Strong, "strong"),
        (NodeKind::Literal, "literal"),
    ] {
        let n = doc.add(kind, Some(p)).unwrap();
        doc.new_text(text, Some(n)).unwrap();
    }
    let out = body(&doc);
    assert!(out.contains("\\emph{em}"), "{out}");
    assert!(out.contains("\\textbf{strong}"), "{out}");
    assert!(out.contains("\\texttt{literal}"), "{out}");
}

#[test]
fn literal_block_uses_sphinx_verbatim() {
    let mut doc = Document::new(None);
    let lb = doc.add(NodeKind::LiteralBlock, Some(doc.root)).unwrap();
    doc.new_text("let x = 1;\nlet y = 2;", Some(lb)).unwrap();
    let out = body(&doc);
    assert!(out.contains("\\begin{sphinxVerbatim}"), "{out}");
    assert!(out.contains("let x = 1;"), "{out}");
    assert!(out.contains("\\end{sphinxVerbatim}"), "{out}");
}

#[test]
fn lists_and_admonitions() {
    let mut doc = Document::new(None);
    let ul = doc.add(NodeKind::BulletList, Some(doc.root)).unwrap();
    let li = doc.add(NodeKind::ListItem, Some(ul)).unwrap();
    doc.new_text("bullet", Some(li)).unwrap();
    let ol = doc.add(NodeKind::EnumeratedList, Some(doc.root)).unwrap();
    let li2 = doc.add(NodeKind::ListItem, Some(ol)).unwrap();
    doc.new_text("number", Some(li2)).unwrap();
    let note = doc.add(NodeKind::Note, Some(doc.root)).unwrap();
    doc.new_text("note body", Some(note)).unwrap();
    let out = body(&doc);
    assert!(out.contains("\\begin{itemize}"), "{out}");
    assert!(out.contains("\\begin{enumerate}"), "{out}");
    assert!(out.contains("\\begin{sphinxadmonition}{note}{Note}"), "{out}");
    assert!(out.contains("note body"), "{out}");
}

#[test]
fn tables_use_tabularx_with_column_spec() {
    let mut doc = Document::new(None);
    let table = doc.add(NodeKind::Table, Some(doc.root)).unwrap();
    let tgroup = doc.add(NodeKind::Tgroup, Some(table)).unwrap();
    for _ in 0..2 {
        doc.add(NodeKind::Colspec, Some(tgroup)).unwrap();
    }
    let tbody = doc.add(NodeKind::Tbody, Some(tgroup)).unwrap();
    let row = doc.add(NodeKind::Row, Some(tbody)).unwrap();
    for text in ["a", "b"] {
        let entry = doc.add(NodeKind::Entry, Some(row)).unwrap();
        doc.new_text(text, Some(entry)).unwrap();
    }
    let out = body(&doc);
    assert!(out.contains("\\begin{tabularx}{\\textwidth}"), "{out}");
    assert!(out.contains("|X|X|"), "{out}");
    assert!(out.contains("a & b"), "{out}");
    assert!(out.contains("\\hline"), "{out}");
    assert!(out.contains("\\end{tabularx}"), "{out}");
}

#[test]
fn references_math_index_and_figures() {
    let mut doc = Document::new(None);
    let p = doc.add(NodeKind::Paragraph, Some(doc.root)).unwrap();
    let mut ref_node = scribe_ast::Node::new(NodeKind::Reference);
    ref_node.set_str("refuri", "https://example.com");
    let rid = doc.add_node(ref_node, Some(p)).unwrap();
    doc.new_text("site", Some(rid)).unwrap();
    let math = doc.add(NodeKind::MathBlock, Some(doc.root)).unwrap();
    doc.get_mut(math).unwrap().set_str("text", "E = mc^2");
    let idx = doc.add(NodeKind::Index, Some(doc.root)).unwrap();
    doc.get_mut(idx).unwrap().set_list("entries", vec!["Einstein".to_owned()]);
    let figure = doc.add(NodeKind::Figure, Some(doc.root)).unwrap();
    let caption = doc.add(NodeKind::Caption, Some(figure)).unwrap();
    doc.new_text("A figure", Some(caption)).unwrap();
    let image = doc.add(NodeKind::Image, Some(figure)).unwrap();
    doc.get_mut(image).unwrap().set_str("uri", "img.png");
    doc.get_mut(image).unwrap().set_str("width", "100px");
    let out = body(&doc);
    assert!(out.contains("\\href{https://example.com}{site}"), "{out}");
    assert!(out.contains("\\[E = mc^2\\]"), "{out}");
    assert!(out.contains("\\index{Einstein}"), "{out}");
    assert!(out.contains("\\begin{figure}[htbp]"), "{out}");
    assert!(out.contains("\\caption{A figure}"), "{out}");
    assert!(out.contains("width=75bp"), "{out}");
}

#[test]
fn howto_uses_section_and_unicode_engine_preserves_unicode() {
    let mut c = ctx();
    c.theme = "howto".to_owned();
    let mut doc = Document::new(None);
    let s = doc.add(NodeKind::Section, Some(doc.root)).unwrap();
    let t = doc.add(NodeKind::Title, Some(s)).unwrap();
    doc.new_text("Hello", Some(t)).unwrap();
    let out = LaTeXTranslator::translate_body(&doc, &c);
    assert!(out.contains("\\section{Hello}"), "{out}");
    assert!(!out.contains("\\chapter"), "{out}");

    let mut c2 = ctx();
    c2.engine = LatexEngine::XeLatex;
    let mut doc2 = Document::new(None);
    let p = doc2.add(NodeKind::Paragraph, Some(doc2.root)).unwrap();
    doc2.new_text("café", Some(p)).unwrap();
    let out2 = LaTeXTranslator::translate_body(&doc2, &c2);
    assert!(out2.contains("café"), "{out2}");
}

#[test]
fn escaping_rules_are_stable() {
    let text = "a%b&c_d#e{f}g~h^i\\j$k[l]";
    let escaped = escape_latex(text, LatexEngine::PdfLatex);
    assert!(escaped.contains("\\%"), "{escaped}");
    assert!(escaped.contains("\\textbackslash{}"), "{escaped}");
    assert!(escaped.contains("{["), "{escaped}");
    assert_eq!(escape_latex_unicode("naïve %"), "naïve \\%");
    assert!(escape_latex("ℯ⁰", LatexEngine::PdfLatex).is_ascii());
}

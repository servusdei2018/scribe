//! Shared helpers for the Phase 25 builder differential tests.

#![allow(dead_code)]

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use scribe_builders::html::BuildOptions;
use scribe_config::{load_config, Config};

/// Workspace root derived from the test crate's manifest location.
pub fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
}

/// Process-unique temporary directory.
pub fn temp_dir(label: &str) -> PathBuf {
    let path = std::env::temp_dir().join(format!(
        "scribe-phase25-{label}-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0)
    ));
    let _ = std::fs::create_dir_all(&path);
    path
}

/// Options used by all Phase 25 builders in the differential tests.
pub fn options(fixture: &Path, out: &Path, builder: &str) -> BuildOptions {
    BuildOptions {
        source_dir: fixture.to_path_buf(),
        output_dir: out.to_path_buf(),
        builder_name: builder.to_owned(),
        freshenv: true,
        worker_count: 4,
        ..BuildOptions::default()
    }
}

/// Load configuration with optional `-D` overrides.
pub fn config(fixture: &Path, overrides: &[(&str, &str)]) -> Config {
    let mut map = BTreeMap::new();
    for (key, value) in overrides {
        map.insert((*key).to_owned(), (*value).to_owned());
    }
    let (config, _) = load_config(fixture, Some(&map), None).expect("fixture config must load");
    config
}

/// Normalize the volatile parts of oracle/scribe XML and pseudo-XML output:
/// the absolute source path and the Docutils generator version comment.
pub fn normalize_doctree(text: &str) -> String {
    let mut out = String::new();
    for line in text.lines() {
        let mut line = line.to_owned();
        if let Some(start) = line.find("source=\"") {
            let value_start = start + "source=\"".len();
            if let Some(end) = line[value_start..].find('"') {
                line.replace_range(value_start..value_start + end, "<SOURCE>");
            }
        }
        if line.starts_with("<!-- Generated by Docutils ") {
            line = "<!-- Generated by Docutils <VERSION> -->".to_owned();
        }
        out.push_str(&line);
        out.push('\n');
    }
    out
}

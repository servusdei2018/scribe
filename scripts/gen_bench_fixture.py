#!/usr/bin/env python3
"""Generate a deterministic, offline, multi-page reStructuredText fixture.

The fixture is used by ``scripts/bench.sh`` to compare ``scribe`` against
``sphinx-build`` on identical source. It intentionally avoids third-party
extensions, intersphinx and autodoc so that both engines perform the same
work with no network access: sections, inline markup, lists, admonitions,
code blocks, simple tables and toctree/xref resolution.

Usage: gen_bench_fixture.py OUTPUT_DIR [PAGE_COUNT]
"""

from __future__ import annotations

import sys
from pathlib import Path

PAGE_TEMPLATE = """Page {n:02d}
{underline}

.. _page-{n:02d}:

This is page {n:02d} of the synthetic benchmark project. It contains a
paragraph with *emphasis*, **strong**, ``literal`` and an inline
:ref:`cross reference <page-{n:02d}>` to itself. Repeated sentences give the
parser a realistic amount of inline markup to chew through. Repeated
sentences give the parser a realistic amount of inline markup to chew
through. Repeated sentences give the parser a realistic amount of inline
markup to chew through.

Section A of page {n:02d}
~~~~~~~~~~~~~~~~~~~~~~~~~

- first bullet item with :doc:`page-{next:02d}`
- second bullet item with :ref:`page-{next:02d}`
- third bullet item with ``inline code``

.. note::

   This is a note admonition. It exercises nested directive content and
   inline markup inside an admonition body.

.. code-block:: python

   def function_{n:02d}(value):
       \"\"\"A docstring for page {n:02d}.\"\"\"
       return value * {n}

Section B of page {n:02d}
~~~~~~~~~~~~~~~~~~~~~~~~~

===== =====
Name  Value
===== =====
alpha {n}
beta  {n2}
gamma {n3}
===== =====

See :doc:`page-{prev:02d}` for the previous page and
:doc:`page-{next:02d}` for the next one.
"""

CONF = """# Generated by scripts/gen_bench_fixture.py -- no external extensions.
project = "scribe benchmark"
author = "scribe benchmark"
extensions = []
master_doc = "index"
html_theme = "basic"
exclude_patterns = []
"""

INDEX_TEMPLATE = """Scribe Benchmark Project
========================

A synthetic multi-page project used to benchmark scribe and sphinx-build on
identical, offline source.

.. toctree::
   :maxdepth: 2
   :caption: Contents

{entries}
"""


def generate(out_dir: Path, page_count: int) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "conf.py").write_text(CONF, encoding="utf-8")
    entries = "\n".join(f"   page-{n:02d}" for n in range(1, page_count + 1))
    (out_dir / "index.rst").write_text(
        INDEX_TEMPLATE.format(entries=entries), encoding="utf-8"
    )

    for n in range(1, page_count + 1):
        next_n = n % page_count + 1
        prev_n = (n - 2) % page_count + 1
        text = PAGE_TEMPLATE.format(
            n=n,
            next=next_n,
            prev=prev_n,
            n2=n * 2,
            n3=n * 3,
            underline="=" * (len(f"Page {n:02d}")),
        )
        (out_dir / f"page-{n:02d}.rst").write_text(text, encoding="utf-8")


def main() -> int:
    if len(sys.argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        return 2
    out_dir = Path(sys.argv[1])
    page_count = int(sys.argv[2]) if len(sys.argv) == 3 else 40
    if page_count < 1:
        print("page_count must be positive", file=sys.stderr)
        return 2
    generate(out_dir, page_count)
    print(f"generated {page_count} pages in {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
